"""North American Numbering Plan helpers for caller-ID selection (specs/16 §6.2 Decision P05-T03c).

`npa_states.json` maps a 3-digit area code (NPA) to the two-letter USPS / Canada Post code of its state,
province, or US territory; it is generated by `scripts/generate_npa_states.py` from the `phonenumbers`
geocoder and drift-checked by a test. Toll-free, non-geographic, and other NANP countries' NPAs are absent.
"""

from __future__ import annotations

import functools
import json
from importlib import resources
from typing import Final

__all__ = ["npa", "same_state", "state_for_npa"]

_NANP_LENGTH: Final = 12  # "+1" and 10 digits


def npa(e164: str) -> str | None:
    """The area code of a `+1` E.164 number with 10 national digits; `None` for anything else."""
    if len(e164) != _NANP_LENGTH or not e164.startswith("+1") or not e164[2:].isdigit():
        return None
    return e164[2:5]


@functools.cache
def _table() -> dict[str, str]:
    raw = resources.files("va_common").joinpath("data", "npa_states.json").read_text(encoding="utf-8")
    table: dict[str, str] = json.loads(raw)
    return table


def state_for_npa(area_code: str) -> str | None:
    """The state/province/territory code of an area code, `None` when it is not geographic or unknown."""
    return _table().get(area_code)


def _state(e164: str) -> str | None:
    area_code = npa(e164)
    return None if area_code is None else state_for_npa(area_code)


def same_state(a_e164: str, b_e164: str) -> bool:
    """Whether both numbers are NANP numbers in the same (known) state or province."""
    state = _state(a_e164)
    return state is not None and state == _state(b_e164)
