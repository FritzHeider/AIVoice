"""The benchmark support module (P04-T13) on the accelerated clock: formulas, report rendering, short runs."""

from __future__ import annotations

import asyncio

import pytest
from pipeline_bench import (
    OVERHEAD_P50_LIMIT_MS,
    REPLY,
    SECTION_CONCURRENCY,
    SECTION_HARNESS,
    SECTION_TITLES,
    SECTION_WALL,
    BenchSection,
    LoopLagProbe,
    Machine,
    bench_brain,
    gross_overhead_ms,
    percentile,
    render_report,
    run_conversation,
    summary_rows,
    turn_overhead_ms,
)

from va_sim.clock import AcceleratedClock
from va_voice.latency import TurnLatency
from va_voice.pipeline import SpeakText

MACHINE = Machine(platform="Linux-x", python="3.12.3", cpus=8, processor="", date="2026-11-01 12:00")


def test_overhead_subtracts_endpointing_and_vendor_latencies() -> None:
    latency = TurnLatency(eot_ms=500, stt_final_ms=100, llm_ttft_ms=200, tts_ttfa_ms=150, e2e_ms=980)
    assert turn_overhead_ms(latency) == 30.0
    assert gross_overhead_ms(latency) == 480.0


def test_unmeasured_vendor_terms_count_as_zero() -> None:
    assert turn_overhead_ms(TurnLatency(eot_ms=400, e2e_ms=412)) == 12.0


@pytest.mark.parametrize("latency", [TurnLatency(eot_ms=400), TurnLatency(e2e_ms=900), TurnLatency()])
def test_overhead_is_none_without_e2e_or_eot(latency: TurnLatency) -> None:
    assert turn_overhead_ms(latency) is None
    assert gross_overhead_ms(latency) is None


@pytest.mark.parametrize(
    ("q", "expected"), [(0, 1.0), (10, 1.0), (50, 5.0), (95, 10.0), (99, 10.0), (100, 10.0)]
)
def test_percentile_is_nearest_rank(q: float, expected: float) -> None:
    values = [float(v) for v in (7, 3, 10, 1, 5, 9, 2, 8, 4, 6)]
    assert percentile(values, q) == expected


def test_percentile_rejects_empty_input_and_bad_q() -> None:
    with pytest.raises(ValueError, match="empty"):
        percentile([], 50)
    with pytest.raises(ValueError, match=r"0\.\.100"):
        percentile([1.0], 101)


def test_summary_rows_format() -> None:
    assert summary_rows("lag", [1.0, 2.0, 4.25]) == [
        ("lag p50", "2.0 ms"),
        ("lag p95", "4.2 ms"),
        ("lag max", "4.2 ms"),
    ]


def test_bench_brain_replies_once_per_turn() -> None:
    brain = bench_brain(3)
    assert len(brain.replies) == 3
    assert all(len(reply) == 1 and isinstance(reply[0], SpeakText) for reply in brain.replies)


def test_report_lists_sections_in_order_with_verdicts() -> None:
    sections = [
        BenchSection(SECTION_CONCURRENCY, (("pipelines", "50"),), passed=False),
        BenchSection(SECTION_HARNESS, (("overhead p50", "0.0 ms"),), passed=True),
    ]
    text = render_report(sections, MACHINE)
    assert text.startswith("# va_voice pipeline benchmarks\n")
    assert "Generated by `uv run pytest -m bench packages/va_voice`" in text
    assert "- Processor: unknown" in text
    assert f"overhead and gross p50 <= {OVERHEAD_P50_LIMIT_MS:.0f} ms" in text
    assert text.index(SECTION_HARNESS) < text.index(SECTION_CONCURRENCY)
    assert SECTION_WALL not in text
    assert "Result: PASS\n\n| Metric | Value |\n|---|---|\n| overhead p50 | 0.0 ms |" in text
    assert "Result: FAIL" in text
    assert text.endswith("| pipelines | 50 |\n")
    assert SECTION_TITLES == (SECTION_HARNESS, SECTION_WALL, SECTION_CONCURRENCY)


async def test_short_conversation_measures_every_turn_within_the_gate() -> None:
    result = await run_conversation(clock=AcceleratedClock(), turns=3)
    assert (result.reports, result.user_turns, result.agent_turns) == (3, 3, 3)
    assert len(result.overheads) == len(result.gross_overheads) == 3
    assert max(result.gross_overheads) <= OVERHEAD_P50_LIMIT_MS
    assert result.late_frames == 0
    assert result.frames_sent >= 3 * len(REPLY) * 5 // 20


async def test_loop_lag_probe_samples_until_stopped() -> None:
    probe = LoopLagProbe()
    stop = asyncio.Event()
    task = asyncio.get_running_loop().create_task(probe.run(stop))
    await asyncio.sleep(0.05)
    stop.set()
    await task
    assert probe.samples_ms
    assert all(sample >= 0 for sample in probe.samples_ms)
