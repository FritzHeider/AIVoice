"""Render ``.env`` as the env file of the compose application services (specs/29 §2 Decision P05-T17a).

``uv run python scripts/compose_env.py [--env-file .env] [--output .env.compose]`` parses the env file
with python-dotenv (the defaults pydantic-settings uses in the services) and writes each assignment as
``KEY='value'``. Docker Compose parses dotenv files differently: ``KEY=  # comment`` (an empty value and a
comment, the ``.env.example`` form of every blank variable) becomes the value ``# comment`` there, so the
containers would see comment text in ``SENTRY_DSN``, ``POD_ID``, and the other blank variables.
Single-quoted values are literal for Compose (no escapes, no ``$`` interpolation). ``scripts/dev_up.sh``
runs this before starting the application services. Exit codes: 0 written, 1 a value Compose cannot
represent (a single quote or a line break), 2 no env file.
"""

from __future__ import annotations

import argparse
import sys
from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import Final

from dotenv import dotenv_values

EXIT_UNREPRESENTABLE: Final = 1
EXIT_USAGE: Final = 2
DEFAULT_ENV_FILE: Final = Path(".env")
DEFAULT_OUTPUT: Final = Path(".env.compose")
HEADER: Final = (
    "# Generated by scripts/compose_env.py from {source} for docker compose; edit {source} instead.\n"
)
_UNREPRESENTABLE: Final = ("'", "\n", "\r")


class UnrepresentableValueError(ValueError):
    """A value Compose cannot read back literally from a single-quoted dotenv value."""

    def __init__(self, key: str) -> None:
        super().__init__(f"{key} contains a single quote or a line break")
        self.key = key


def render(values: Mapping[str, str | None], source: str) -> str:
    """The Compose env file for ``values``; keys without ``=`` (value ``None``) are left out."""
    lines = [HEADER.format(source=source)]
    for key, value in values.items():
        if value is None:
            continue
        if any(char in value for char in _UNREPRESENTABLE):
            raise UnrepresentableValueError(key)
        lines.append(f"{key}='{value}'\n")
    return "".join(lines)


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Render .env for the docker compose application services.")
    parser.add_argument(
        "--env-file", type=Path, default=DEFAULT_ENV_FILE, help="source env file (default .env)"
    )
    parser.add_argument(
        "--output", type=Path, default=DEFAULT_OUTPUT, help="file to write (default .env.compose)"
    )
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    args = _parser().parse_args(argv)
    source: Path = args.env_file
    if not source.is_file():
        print(f"compose_env: env file not found: {source}", file=sys.stderr)
        return EXIT_USAGE
    try:
        text = render(dotenv_values(source), source.name)
    except UnrepresentableValueError as error:
        print(f"compose_env: {error}; Compose cannot read it from an env file", file=sys.stderr)
        return EXIT_UNREPRESENTABLE
    output: Path = args.output
    output.write_text(text, encoding="utf-8")
    print(f"compose_env: wrote {output}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
