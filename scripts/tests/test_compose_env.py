"""``scripts/compose_env.py``: `.env` rendered literally for docker compose (specs/29 §2 P05-T17a)."""

from __future__ import annotations

import shutil
import subprocess
from pathlib import Path

import pytest
import yaml

import compose_env

SOURCE = """# local settings
VA_ENV=local  # environment
SENTRY_DSN=  # backend Sentry DSN; empty disables reporting
POD_ID=
QUOTED="a b"  # quoted
PRICE=$5 and ${HOME_NOT_SET}
BARE_KEY
"""


def _write(tmp_path: Path, text: str) -> Path:
    path = tmp_path / ".env"
    path.write_text(text, encoding="utf-8")
    return path


def test_blank_values_with_comments_render_empty(tmp_path: Path) -> None:
    source = _write(tmp_path, SOURCE)
    output = tmp_path / ".env.compose"
    assert compose_env.main(["--env-file", str(source), "--output", str(output)]) == 0
    lines = output.read_text(encoding="utf-8").splitlines()
    assert lines[0].startswith("# Generated by scripts/compose_env.py from .env")
    assert lines[1:5] == ["VA_ENV='local'", "SENTRY_DSN=''", "POD_ID=''", "QUOTED='a b'"]
    assert lines[5].startswith("PRICE='$5 and ")
    assert not any(line.startswith("BARE_KEY") for line in lines)


@pytest.mark.parametrize("value", ["it's", '"line\\nbreak"'])
def test_values_compose_cannot_read_literally_exit_1(
    tmp_path: Path, value: str, capsys: pytest.CaptureFixture[str]
) -> None:
    source = _write(tmp_path, f"BAD={value}\n")
    output = tmp_path / ".env.compose"
    assert (
        compose_env.main(["--env-file", str(source), "--output", str(output)])
        == compose_env.EXIT_UNREPRESENTABLE
    )
    assert "BAD contains a single quote or a line break" in capsys.readouterr().err
    assert not output.exists()


def test_missing_env_file_exits_2(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    assert compose_env.main(["--env-file", str(tmp_path / "absent.env")]) == compose_env.EXIT_USAGE
    assert "env file not found" in capsys.readouterr().err


@pytest.mark.skipif(shutil.which("docker") is None, reason="docker CLI not installed")
def test_compose_reads_the_rendered_values_literally(tmp_path: Path) -> None:
    source = _write(tmp_path, SOURCE.replace("PRICE=$5 and ${HOME_NOT_SET}\n", "PRICE=$$5\n"))
    output = tmp_path / ".env.compose"
    assert compose_env.main(["--env-file", str(source), "--output", str(output)]) == 0
    (tmp_path / "compose.yml").write_text(
        "services:\n  s:\n    image: alpine\n    env_file: [.env.compose]\n", encoding="utf-8"
    )
    result = subprocess.run(
        ["docker", "compose", "config"],
        cwd=tmp_path,
        check=True,
        capture_output=True,
        text=True,
        timeout=60,
    )
    environment = yaml.safe_load(result.stdout)["services"]["s"]["environment"]
    # `compose config` prints a literal `$` as `$$`: the stored value is the literal `$$5`.
    expected = {"VA_ENV": "local", "SENTRY_DSN": "", "POD_ID": "", "QUOTED": "a b", "PRICE": "$$$$5"}
    assert environment == expected
